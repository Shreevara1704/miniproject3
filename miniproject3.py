import pandas as pd          # Library for data manipulation and analysis
import seaborn as sns        # Library for statistical data visualization
import matplotlib.pyplot as plt  # Library for creating plots and charts

# Group the data by 'city' and 'category'
# .size() counts the number of records (orders) in each city-category combination
# .unstack(fill_value=0) converts categories into columns
# fill_value=0 replaces missing combinations with 0 instead of NaN
city_category_counts = df.groupby(['city', 'category']).size().unstack(fill_value=0)

# Create a new figure
# figsize=(10,6) sets width=10 inches and height=6 inches
plt.figure(figsize=(10,6))

# Draw the heatmap
sns.heatmap(
    city_category_counts,  # Data matrix to visualize

    annot=True,            # Display the count value inside each cell

    fmt='d',               # Format annotations as integers ('d' = decimal integer)

    cmap='viridis'         # Color palette:
                           # Dark purple = low values
                           # Yellow = high values
)

# Label for x-axis (columns represent categories)
plt.xlabel('category')

# Label for y-axis (rows represent cities)
plt.ylabel('city')

# Title of the heatmap
plt.title('City vs Category (Order Count)')

# Display the plot
plt.show()

